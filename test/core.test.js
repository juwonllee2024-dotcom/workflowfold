import test from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, rm, unlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import {
  buildProject,
  checkProject,
  createPlan,
  mapSourceToDestination,
} from "../src/core.js";

test("maps nested workflow sources to deterministic flat names", () => {
  assert.equal(
    mapSourceToDestination("services/api/ci.yml"),
    "services-api-ci.yml",
  );
  assert.equal(
    mapSourceToDestination("release/nightly.yaml"),
    "release-nightly.yml",
  );
});

test("rejects two source paths that map to the same generated file", () => {
  assert.throws(
    () => createPlan(["a/b.yml", "a-b.yml"]),
    /collision/i,
  );
});

test("builds generated workflows and detects later drift", async () => {
  const root = await mkdtemp(join(tmpdir(), "workflowfold-"));
  try {
    const source = join(root, ".github", "workflow-src", "services", "api");
    await mkdir(source, { recursive: true });
    await writeFile(
      join(source, "ci.yml"),
      "name: API CI\non: [push]\njobs:\n  test:\n    runs-on: ubuntu-latest\n    steps: []\n",
      "utf8",
    );

    const built = await buildProject({ root });
    assert.equal(built.entries.length, 1);

    const generatedPath = join(root, ".github", "workflows", "services-api-ci.yml");
    const generated = await readFile(generatedPath, "utf8");
    assert.match(generated, /Generated by workflowfold/);
    assert.equal((await checkProject({ root })).ok, true);

    await writeFile(generatedPath, `${generated}\n# accidental edit\n`, "utf8");
    const checked = await checkProject({ root });
    assert.equal(checked.ok, false);
    assert.match(checked.errors.join("\n"), /drift/i);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("refuses to overwrite an unmanaged workflow", async () => {
  const root = await mkdtemp(join(tmpdir(), "workflowfold-"));
  try {
    const source = join(root, ".github", "workflow-src");
    const destination = join(root, ".github", "workflows");
    await mkdir(source, { recursive: true });
    await mkdir(destination, { recursive: true });
    await writeFile(join(source, "ci.yml"), "name: CI\n", "utf8");
    await writeFile(join(destination, "ci.yml"), "name: Handwritten\n", "utf8");

    await assert.rejects(
      buildProject({ root }),
      /unmanaged/i,
    );
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("requires explicit prune before removing a stale generated workflow", async () => {
  const root = await mkdtemp(join(tmpdir(), "workflowfold-"));
  try {
    const source = join(root, ".github", "workflow-src");
    await mkdir(source, { recursive: true });
    const sourcePath = join(source, "ci.yml");
    await writeFile(sourcePath, "name: CI\n", "utf8");
    await buildProject({ root });
    await unlink(sourcePath);

    await assert.rejects(buildProject({ root }), /stale generated workflows/i);
    const pruned = await buildProject({ root, prune: true });
    assert.deepEqual(pruned.pruned, [".github/workflows/ci.yml"]);
    assert.equal((await checkProject({ root })).ok, true);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
