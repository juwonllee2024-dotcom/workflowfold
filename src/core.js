import { createHash } from "node:crypto";
import { access, mkdir, readdir, readFile, unlink, writeFile } from "node:fs/promises";
import { basename, dirname, join, relative, resolve, sep } from "node:path";

export const DEFAULT_SOURCE_DIR = ".github/workflow-src";
export const DEFAULT_DEST_DIR = ".github/workflows";
export const DEFAULT_MANIFEST_PATH = ".workflowfold/manifest.json";
export const GENERATED_MARKER = "# Generated by workflowfold.";

const yamlExtension = /\.(?:ya?ml)$/i;

function toPosix(value) {
  return value.split(sep).join("/").replaceAll("\\", "/");
}

function normalizeRelativePath(value) {
  const normalized = toPosix(value).replace(/^\.\//, "");
  if (!normalized || normalized.startsWith("/") || normalized.split("/").includes("..")) {
    throw new Error(`Path must stay inside the project: ${value}`);
  }
  return normalized;
}

function projectPath(root, child) {
  const rootPath = resolve(root);
  const childPath = resolve(rootPath, child);
  const childRelative = relative(rootPath, childPath);
  if (childRelative === ".." || childRelative.startsWith(`..${sep}`)) {
    throw new Error(`Path escapes project root: ${child}`);
  }
  return childPath;
}

function hash(value) {
  return createHash("sha256").update(value, "utf8").digest("hex");
}

export function mapSourceToDestination(sourcePath) {
  const normalized = normalizeRelativePath(sourcePath);
  if (!yamlExtension.test(normalized)) {
    throw new Error(`Workflow source must end in .yml or .yaml: ${sourcePath}`);
  }

  const withoutExtension = normalized.replace(yamlExtension, "");
  const slug = withoutExtension
    .split("/")
    .map((part) => part.replace(/[^A-Za-z0-9_-]+/g, "-")
      .replace(/-+/g, "-")
      .replace(/^-+|-+$/g, ""))
    .filter(Boolean)
    .join("-")
    .toLowerCase();

  if (!slug) {
    throw new Error(`Workflow source has no usable generated name: ${sourcePath}`);
  }
  return `${slug}.yml`;
}

export function createPlan(sourcePaths) {
  const entries = sourcePaths
    .map((source) => {
      const normalizedSource = normalizeRelativePath(source);
      return {
        source: normalizedSource,
        destination: mapSourceToDestination(normalizedSource),
      };
    })
    .sort((left, right) => left.source.localeCompare(right.source));

  const destinations = new Map();
  for (const entry of entries) {
    const previous = destinations.get(entry.destination);
    if (previous) {
      throw new Error(
        `Generated filename collision: ${previous} and ${entry.source} both map to ${entry.destination}`,
      );
    }
    destinations.set(entry.destination, entry.source);
  }
  return entries;
}

export function generatedContent(sourcePath, sourceContent) {
  return `${GENERATED_MARKER} DO NOT EDIT THIS FILE DIRECTLY.\n# Source: ${sourcePath}\n\n${sourceContent}`;
}

async function pathExists(path) {
  try {
    await access(path);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

async function discoverFiles(directory, rootDirectory) {
  if (!(await pathExists(directory))) return [];

  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const absolute = join(directory, entry.name);
    if (entry.isSymbolicLink()) {
      throw new Error(`Symbolic links are not supported in workflow sources: ${absolute}`);
    }
    if (entry.isDirectory()) {
      files.push(...await discoverFiles(absolute, rootDirectory));
    } else if (entry.isFile() && yamlExtension.test(entry.name)) {
      files.push(toPosix(relative(rootDirectory, absolute)));
    }
  }
  return files;
}

async function discoverPlan(root, sourceDir) {
  const sourceRoot = projectPath(root, sourceDir);
  const sourcePaths = await discoverFiles(sourceRoot, sourceRoot);
  const plan = createPlan(sourcePaths);
  const sourcePrefix = sourceDir === "." ? "" : normalizeRelativePath(sourceDir);
  return plan.map((entry) => ({
    ...entry,
    source: sourcePrefix ? `${sourcePrefix}/${entry.source}` : entry.source,
  }));
}

async function readManifest(root, manifestPath) {
  const absolute = projectPath(root, manifestPath);
  if (!(await pathExists(absolute))) return null;

  let parsed;
  try {
    parsed = JSON.parse(await readFile(absolute, "utf8"));
  } catch (error) {
    throw new Error(`Cannot read manifest ${manifestPath}: ${error.message}`);
  }
  if (parsed?.version !== 1 || !Array.isArray(parsed.entries)) {
    throw new Error(`Unsupported workflowfold manifest: ${manifestPath}`);
  }
  return parsed;
}

async function writeManifest(root, manifestPath, entries) {
  const absolute = projectPath(root, manifestPath);
  await mkdir(dirname(absolute), { recursive: true });
  const manifest = {
    version: 1,
    generatedBy: "workflowfold",
    entries: entries
      .slice()
      .sort((left, right) => left.source.localeCompare(right.source)),
  };
  await writeFile(absolute, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");
}

async function generatedDestinationNames(root, destinationDir) {
  const directory = projectPath(root, destinationDir);
  if (!(await pathExists(directory))) return [];
  const files = await readdir(directory, { withFileTypes: true });
  const generated = [];
  for (const file of files) {
    if (!file.isFile() || !yamlExtension.test(file.name)) continue;
    const content = await readFile(join(directory, file.name), "utf8");
    if (content.startsWith(GENERATED_MARKER)) generated.push(file.name);
  }
  return generated.sort();
}

async function staleEntries(root, previous, currentEntries) {
  if (!previous) return [];
  const current = new Set(currentEntries.map((entry) => entry.source));
  return previous.entries.filter((entry) => !current.has(entry.source));
}

export async function buildProject({
  root = process.cwd(),
  sourceDir = DEFAULT_SOURCE_DIR,
  destinationDir = DEFAULT_DEST_DIR,
  manifestPath = DEFAULT_MANIFEST_PATH,
  prune = false,
} = {}) {
  const projectRoot = resolve(root);
  const plan = await discoverPlan(projectRoot, sourceDir);
  const previous = await readManifest(projectRoot, manifestPath);
  const stale = await staleEntries(projectRoot, previous, plan);

  if (stale.length && !prune) {
    const paths = stale.map((entry) => entry.destination).join(", ");
    throw new Error(`Stale generated workflows found (${paths}); rerun with --prune to remove only recorded outputs`);
  }

  for (const entry of stale) {
    const output = projectPath(projectRoot, entry.destination);
    if (!(await pathExists(output))) continue;
    const content = await readFile(output, "utf8");
    if (!content.startsWith(GENERATED_MARKER)) {
      throw new Error(`Refusing to delete unmanaged workflow: ${output}`);
    }
    await unlink(output);
  }

  const manifestEntries = [];
  for (const entry of plan) {
    const source = projectPath(projectRoot, entry.source);
    const destination = projectPath(projectRoot, join(destinationDir, entry.destination));
    const sourceContent = await readFile(source, "utf8");
    if (await pathExists(destination)) {
      const existing = await readFile(destination, "utf8");
      if (!existing.startsWith(GENERATED_MARKER)) {
        throw new Error(`Refusing to overwrite unmanaged workflow: ${destination}`);
      }
    }
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, generatedContent(entry.source, sourceContent), "utf8");
    manifestEntries.push({
      source: entry.source,
      destination: join(destinationDir, entry.destination).split(sep).join("/"),
      sha256: hash(sourceContent),
    });
  }

  await writeManifest(projectRoot, manifestPath, manifestEntries);
  return { entries: manifestEntries, pruned: stale.map((entry) => entry.destination) };
}

export async function checkProject({
  root = process.cwd(),
  sourceDir = DEFAULT_SOURCE_DIR,
  destinationDir = DEFAULT_DEST_DIR,
  manifestPath = DEFAULT_MANIFEST_PATH,
} = {}) {
  const projectRoot = resolve(root);
  const errors = [];
  let plan;
  let manifest;
  try {
    plan = await discoverPlan(projectRoot, sourceDir);
    manifest = await readManifest(projectRoot, manifestPath);
  } catch (error) {
    return { ok: false, errors: [error.message], entries: [] };
  }

  if (!manifest) {
    errors.push(`Manifest missing: ${manifestPath}; run workflowfold build`);
    return { ok: false, errors, entries: [] };
  }

  const expected = [];
  for (const entry of plan) {
    try {
      const sourceContent = await readFile(projectPath(projectRoot, entry.source), "utf8");
      const destination = join(destinationDir, entry.destination).split(sep).join("/");
      const expectedEntry = {
        source: entry.source,
        destination,
        sha256: hash(sourceContent),
      };
      expected.push(expectedEntry);
      const recorded = manifest.entries.find((item) => item.source === entry.source);
      if (JSON.stringify(recorded) !== JSON.stringify(expectedEntry)) {
        errors.push(`Manifest drift for ${entry.source}`);
      }

      const output = projectPath(projectRoot, destination);
      if (!(await pathExists(output))) {
        errors.push(`Generated workflow missing: ${destination}`);
      } else if (await readFile(output, "utf8") !== generatedContent(entry.source, sourceContent)) {
        errors.push(`Generated workflow drift: ${destination}`);
      }
    } catch (error) {
      errors.push(error.message);
    }
  }

  const expectedSources = new Set(expected.map((entry) => entry.source));
  for (const entry of manifest.entries) {
    if (!expectedSources.has(entry.source)) {
      errors.push(`Stale manifest entry: ${entry.source}`);
    }
  }

  const recordedDestinations = new Set(manifest.entries.map((entry) => entry.destination));
  for (const name of await generatedDestinationNames(projectRoot, destinationDir)) {
    const destination = `${destinationDir}/${name}`;
    if (!recordedDestinations.has(destination)) {
      errors.push(`Untracked generated workflow: ${destination}`);
    }
  }

  return { ok: errors.length === 0, errors, entries: expected };
}

export async function listProject({
  root = process.cwd(),
  sourceDir = DEFAULT_SOURCE_DIR,
} = {}) {
  const projectRoot = resolve(root);
  return discoverPlan(projectRoot, sourceDir);
}

export function displayName(path) {
  return basename(path);
}
